/** Write through a temp file; on any failure the previous bytes are restored. */
async function atomicWrite(path: string, content: string): Promise<void> {
  const temp = `${path}.${process.pid}.tmp`;
  let previous: string | null = null;
  try {
    previous = await readFile(path, "utf8");
  } catch {
    previous = null;
  }
  try {
    await writeFile(temp, content, "utf8");
    await rename(temp, path);
    const back = await readFile(path, "utf8");
    if (back !== content) {
      throw new Error(`write verification failed: ${path}`);
    }
  } catch (error) {
    await rm(temp, { force: true }).catch(() => undefined);
    if (previous !== null) {
      await writeFile(path, previous, "utf8").catch(() => undefined);
    }
    throw error;
  }
}

async function fileExists(path: string): Promise<boolean> {
  try {
    await readFile(path, "utf8");
    return true;
  } catch {
    return false;
  }
}

/** Read users; a missing file is an empty list, a broken file is an error. */
async function readUsers(dir: string): Promise<ExternalUser[]> {
  let raw: string;
  try {
    raw = await readFile(join(dir, USERS_FILE), "utf8");
  } catch (error) {
    if ((error as { code?: string }).code === "ENOENT") return [];
    throw error;
  }
  const parsed = parseUsers(raw);
  if (!parsed) {
    throw new Error(
      `${USERS_FILE} is unreadable — fix or remove it before editing the list.`,
    );
  }
  return parsed.users;
}

async function writeUsers(dir: string, users: ExternalUser[]): Promise<void> {
  await mkdir(dir, { recursive: true });
  await atomicWrite(join(dir, USERS_FILE), serializeUsers(users));
}

/** Read services; a missing file is an empty list, a broken file is an error. */
async function readServices(dir: string): Promise<ExternalService[]> {
  let raw: string;
  try {
    raw = await readFile(join(dir, SERVICES_FILE), "utf8");
  } catch (error) {
    if ((error as { code?: string }).code === "ENOENT") return [];
    throw error;
  }
  const parsed = parseServices(raw);
  if (!parsed) {
    throw new Error(
      `${SERVICES_FILE} is unreadable — fix or remove it before editing the list.`,
    );
  }
  return parsed.services;
}

async function writeServices(
  dir: string,
  services: ExternalService[],
): Promise<void> {
  await mkdir(dir, { recursive: true });
  await atomicWrite(join(dir, SERVICES_FILE), serializeServices(services));
}

/** A missing services.json must not replace a snippet that still routes traffic. */
async function ensureLiveServices(dir: string): Promise<void> {
  if (await fileExists(join(dir, SERVICES_FILE))) return;
  let previous = "";
  try {
    previous = await readFile(join(dir, SERVICES_SNIPPET_FILE), "utf8");
  } catch {
    previous = "";
  }
  const live = previous
    .split("\n")
    .some((line) => line.trim() && !line.startsWith("#"));
  if (live) {
    throw new Error(
      `${SERVICES_FILE} is missing — refusing to empty the live Caddy services snippet.`,
    );
  }
}

interface SnippetWrite {
  path: string;
  blocks: number;
  changed: boolean;
}

async function writeServicesSnippet(
  dir: string,
  services: ExternalService[],
): Promise<SnippetWrite> {
  await mkdir(dir, { recursive: true });
  const path = join(dir, SERVICES_SNIPPET_FILE);
  const content = caddyServicesSnippet(services, join(dir, SNIPPET_FILE));
  let previous = "";
  try {
    previous = await readFile(path, "utf8");
  } catch {
    previous = "";
  }
  if (previous !== content) await atomicWrite(path, content);
  return {
    path,
    blocks: services.filter((service) => service.enabled).length,
    changed: previous !== content,
  };
}

async function writeSiteSnippet(
  dir: string,
  services: ExternalService[],
  host: string | null,
): Promise<SnippetWrite> {
  const sites = services.filter((service) => service.kind === "site");
  if (sites.length > 0 && !host) {
    throw new Error("Set the public URL before adding a site service.");
  }
  await mkdir(dir, { recursive: true });
  const path = join(dir, SITES_SNIPPET_FILE);
  const content = caddySitesSnippet(
    services,
    host ?? "",
    join(dir, SNIPPET_FILE),
  );
  let previous = "";
  try {
    previous = await readFile(path, "utf8");
  } catch {
    previous = "";
  }
  if (previous !== content) await atomicWrite(path, content);
  return {
    path,
    blocks: sites.filter((service) => service.enabled).length,
    changed: previous !== content,
  };
}

