/** Run validate first; a failed check never reaches reload. */
export async function validateThenReload(
  run: (command: string) => Promise<RunResult>,
  validate: string,
  reload: string,
): Promise<RunResult> {
  const check = await run(validate);
  if (!check.ok) return check;
  return run(reload);
}

export interface RunResult {
  ok: boolean;
  command: string;
  code: number | string;
  output: string;
}

function run(command: string, cwd: string): Promise<RunResult> {
  return new Promise((resolve) => {
    exec(
      command,
      { cwd, timeout: 15_000, windowsHide: true },
      (error, stdout, stderr) => {
        const output = [stdout ?? "", stderr ?? "", error?.message ?? ""]
          .map((part) => part.trim())
          .filter(Boolean)
          .join("\n");
        resolve({
          ok: !error,
          command,
          code: error ? ((error as { code?: number | string }).code ?? 1) : 0,
          output,
        });
      },
    );
  });
}

async function status(api: PluginApi): Promise<unknown> {
  const dir = text(api.settings.dir);
  if (!dir) {
    return {
      folder: { path: "", writable: false },
      users: {
        count: 0,
        enabled: 0,
        problem:
          "Set the data folder in the plugin settings (Advanced → Plugins → Caddy services).",
      },
      snippet: { path: "", exists: false, current: false, users: 0 },
      services: {
        count: 0,
        enabled: 0,
        problem:
          "Set the data folder in the plugin settings (Advanced → Plugins → Caddy services).",
      },
      servicesSnippet: { path: "", exists: false, current: false, blocks: 0 },
      sitesSnippet: { path: "", exists: false, current: false, blocks: 0 },
      caddy: {
        config: caddyConfig(api),
        validateCommand: validateCommand(api),
        reloadCommand: reloadCommand(api),
        importsSnippet: null,
        importsSites: null,
      },
      publicUrl: {},
    };
  }
  let writable = true;
  try {
    await mkdir(dir, { recursive: true });
    const probe = join(dir, `.probe-${process.pid}`);
    await writeFile(probe, "ok", "utf8");
    await rm(probe, { force: true });
  } catch {
    writable = false;
  }

  let users: ExternalUser[] = [];
  let problem: string | undefined;
  try {
    users = await readUsers(dir);
  } catch (error) {
    problem = error instanceof Error ? error.message : String(error);
  }

  let snippetText: string | null = null;
  try {
    snippetText = await readFile(join(dir, SNIPPET_FILE), "utf8");
  } catch {
    snippetText = null;
  }
  const expected = caddySnippet(users);

  let services: ExternalService[] = [];
  let servicesProblem: string | undefined;
  let servicesReadable = true;
  try {
    services = await readServices(dir);
  } catch (error) {
    servicesReadable = false;
    servicesProblem = error instanceof Error ? error.message : String(error);
  }
  let servicesSnippetText: string | null = null;
  try {
    servicesSnippetText = await readFile(
      join(dir, SERVICES_SNIPPET_FILE),
      "utf8",
    );
  } catch {
    servicesSnippetText = null;
  }
  const servicesExpected = servicesReadable
    ? caddyServicesSnippet(services, join(dir, SNIPPET_FILE))
    : null;
  const siteServices = services.filter((service) => service.kind === "site");
  const host = siteHost(api);
  const sitesExpected =
    servicesReadable && (siteServices.length === 0 || host)
      ? caddySitesSnippet(services, host ?? "", join(dir, SNIPPET_FILE))
      : null;
  let sitesSnippetText: string | null = null;
  try {
    sitesSnippetText = await readFile(join(dir, SITES_SNIPPET_FILE), "utf8");
  } catch {
    sitesSnippetText = null;
  }
  let caddyText: string | null = null;
  try {
    caddyText = await readFile(caddyConfig(api), "utf8");
  } catch {
    caddyText = null;
  }
  const importsSnippet =
    caddyText === null
      ? null
      : caddyText.includes(join(dir, SERVICES_SNIPPET_FILE));
  const importsSites =
    caddyText === null
      ? null
      : caddyText.includes(join(dir, SITES_SNIPPET_FILE));

  const url = text(api.settings.publicUrl);
  let publicUrl: Record<string, unknown> = { url };
  if (url) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4000);
    try {
      const response = await fetch(url, {
        method: "HEAD",
        signal: controller.signal,
      });
      const protectedSite = response.status === 401 || response.status === 403;
      publicUrl = {
        url,
        status: response.status,
        ok: response.ok || protectedSite,
        ...(protectedSite ? { protected: true } : {}),
      };
    } catch (error) {
      publicUrl = {
        url,
        error: error instanceof Error ? error.message : String(error),
      };
    } finally {
      clearTimeout(timer);
    }
  }

  return {
    folder: { path: dir, writable },
    users: {
      count: users.length,
      enabled: users.filter((user) => user.enabled).length,
      ...(problem ? { problem } : {}),
    },
    snippet: {
      path: join(dir, SNIPPET_FILE),
      exists: snippetText !== null,
      current: snippetText === expected,
      users: expected ? expected.trimEnd().split("\n").length : 0,
    },
    services: {
      count: services.length,
      enabled: services.filter((service) => service.enabled).length,
      ...(servicesProblem ? { problem: servicesProblem } : {}),
    },
    servicesSnippet: {
      path: join(dir, SERVICES_SNIPPET_FILE),
      exists: servicesSnippetText !== null,
      current:
        servicesExpected !== null && servicesSnippetText === servicesExpected,
      blocks: services.filter(
        (service) => service.enabled && service.kind !== "site",
      ).length,
    },
    sitesSnippet: {
      path: join(dir, SITES_SNIPPET_FILE),
      exists: sitesSnippetText !== null,
      current: sitesExpected !== null && sitesSnippetText === sitesExpected,
      blocks: siteServices.filter((service) => service.enabled).length,
    },
    caddy: {
      config: caddyConfig(api),
      validateCommand: validateCommand(api),
      reloadCommand: reloadCommand(api),
      importsSnippet,
      importsSites,
    },
    publicUrl,
  };
}

function conflictProblem(
  services: ExternalService[],
  service: ExternalService,
  ignoreId?: string,
): string | null {
  for (const other of services) {
    if (other.id === ignoreId) continue;
    if (other.id === service.id) {
      return `A service with the id ${service.id} already exists.`;
    }
    if (other.kind === "site" || service.kind === "site") {
      if (
        other.kind === "site" &&
        service.kind === "site" &&
        other.port === service.port
      ) {
        return `The port ${service.port} is already used by the site ${other.id}.`;
      }
      continue;
    }
    if (other.path === service.path) {
      return `The path ${service.path} is already used.`;
    }
    if (pathsConflict(other.path ?? "", service.path ?? "")) {
      return `The path ${service.path} overlaps the service ${other.path}.`;
    }
  }
  return null;
}

async function handle(api: PluginApi, payload: unknown): Promise<unknown> {
  const request =
    payload && typeof payload === "object"
      ? (payload as Record<string, unknown>)
      : {};
  const action = text(request.action);
  const dir = action === "status" ? "" : folder(api);

  switch (action) {
    case "users.list": {
      const users = await readUsers(dir);
      return { users: publicUsers(users) };
    }
    case "users.add": {
      const user = request.user;
      const password = request.password;
      if (!validateUsername(user)) {
        throw new Error(
          "The user name is not valid (letters, digits, . _ -, max 32).",
        );
      }
      if (!validatePassword(password)) {
        throw new Error(
          `The password must be at least ${MIN_PASSWORD} characters.`,
        );
      }
      const users = await readUsers(dir);
      if (users.some((entry) => entry.user === user)) {
        throw new Error(`The user ${user} already exists.`);
      }
      const hash = await bcrypt.hash(password, HASH_COST);
      const note = text(request.note);
      users.push({ user, hash, ...(note ? { note } : {}), enabled: true });
      await writeUsers(dir, users);
      return { users: publicUsers(users) };
    }
    case "users.setEnabled": {
      const user = request.user;
      const users = await readUsers(dir);
      const entry = users.find((item) => item.user === user);
      if (!entry) throw new Error(`Unknown user: ${String(user)}`);
      if (typeof request.enabled !== "boolean") {
        throw new Error("enabled must be true or false.");
      }
      entry.enabled = request.enabled;
      await writeUsers(dir, users);
      return { users: publicUsers(users) };
    }
    case "users.remove": {
      const user = request.user;
      const users = await readUsers(dir);
      if (!users.some((item) => item.user === user)) {
        throw new Error(`Unknown user: ${String(user)}`);
      }
      const next = users.filter((item) => item.user !== user);
      await writeUsers(dir, next);
      return { users: publicUsers(next) };
    }
    case "services.list": {
      const services = await readServices(dir);
      return { services };
    }
    case "services.add": {
      await ensureLiveServices(dir);
      const read = readService(request.service);
      if ("problem" in read) throw new Error(read.problem);
      const services = await readServices(dir);
      const conflict = conflictProblem(services, read.service);
      if (conflict) throw new Error(conflict);
      const next = [...services, read.service];
      const hostProblem = siteHostProblem(next, siteHost(api));
      if (hostProblem) throw new Error(hostProblem);
      await writeServices(dir, next);
      const servicesSnippet = await writeServicesSnippet(dir, next);
      const sitesSnippet = await writeSiteSnippet(dir, next, siteHost(api));
      return { services: next, snippet: servicesSnippet, sites: sitesSnippet };
    }
    case "services.update": {
      const read = readService(request.service);
      if ("problem" in read) throw new Error(read.problem);
      const services = await readServices(dir);
      const index = services.findIndex((entry) => entry.id === read.service.id);
      if (index < 0) throw new Error(`Unknown service: ${read.service.id}`);
      const conflict = conflictProblem(services, read.service, read.service.id);
      if (conflict) throw new Error(conflict);
      const next = services.map((entry, at) =>
        at === index ? read.service : entry,
      );
      const hostProblem = siteHostProblem(next, siteHost(api));
      if (hostProblem) throw new Error(hostProblem);
      await writeServices(dir, next);
      const servicesSnippet = await writeServicesSnippet(dir, next);
      const sitesSnippet = await writeSiteSnippet(dir, next, siteHost(api));
      return { services: next, snippet: servicesSnippet, sites: sitesSnippet };
    }
    case "services.remove": {
      const id = text(request.id);
      const services = await readServices(dir);
      if (!services.some((entry) => entry.id === id)) {
        throw new Error(`Unknown service: ${id || "(none)"}`);
      }
      const next = services.filter((entry) => entry.id !== id);
      const hostProblem = siteHostProblem(next, siteHost(api));
      if (hostProblem) throw new Error(hostProblem);
      await writeServices(dir, next);
      const servicesSnippet = await writeServicesSnippet(dir, next);
      const sitesSnippet = await writeSiteSnippet(dir, next, siteHost(api));
      return { services: next, snippet: servicesSnippet, sites: sitesSnippet };
    }
    case "services.write": {
      await ensureLiveServices(dir);
      const services = await readServices(dir);
      const hostProblem = siteHostProblem(services, siteHost(api));
      if (hostProblem) throw new Error(hostProblem);
      const servicesSnippet = await writeServicesSnippet(dir, services);
      const sitesSnippet = await writeSiteSnippet(dir, services, siteHost(api));
      return {
        ...servicesSnippet,
        changed: servicesSnippet.changed || sitesSnippet.changed,
        sites: sitesSnippet,
      };
    }
    case "site.pair": {
      const id = text(request.id);
      const services = await readServices(dir);
      const service = services.find((entry) => entry.id === id);
      if (!service || service.kind !== "site") {
        throw new Error(`Unknown site service: ${id || "(none)"}`);
      }
      const upstream = upstreamParts(service.upstream);
      if (!loopbackHost(upstream.host)) {
        throw new Error(
          "Pairing needs a loopback upstream (127.0.0.1, localhost or [::1]).",
        );
      }
      const host = siteHost(api);
      if (!host) throw new Error("Set the public URL before pairing.");
      if (!service.port) throw new Error("The site has no port.");
      const passwordFile =
        text(api.settings.opencodePasswordFile) ||
        "/opt/iobroker/opencode-password";
      let password = "";
      try {
        password = (await readFile(passwordFile, "utf8")).trim();
      } catch {
        throw new Error(`Read the OpenCode password from ${passwordFile}.`);
      }
      if (!password) {
        throw new Error(`The OpenCode password file ${passwordFile} is empty.`);
      }
      const auth = `Basic ${Buffer.from(`opencode:${password}`).toString("base64")}`;
      const base = `http://${upstream.host}:${upstream.port}`;
      const pair = await fetchJson(`${base}/api/pair`, {
        method: "POST",
        headers: { authorization: auth },
      });
      if (pair.status < 200 || pair.status >= 300) {
        throw new Error(
          `The OpenCode server at ${service.upstream} did not return a pairing code (HTTP ${pair.status}).`,
        );
      }
      const code =
        record(pair.body) && typeof pair.body.code === "string"
          ? pair.body.code
          : "";
      if (!code) {
        throw new Error("The OpenCode server did not return a pairing code.");
      }
      const expiresIn =
        record(pair.body) && typeof pair.body.expires_in === "number"
          ? pair.body.expires_in
          : 300;
      let internal: string | undefined;
      try {
        const info = await fetchJson(`${base}/api/info`, {
          headers: { authorization: auth },
        });
        if (info.status >= 200 && info.status < 300 && record(info.body)) {
          const urls = Array.isArray(info.body.urls) ? info.body.urls : [];
          const lan = urls.find((url): url is string => {
            if (typeof url !== "string") return false;
            try {
              return !loopbackHost(new URL(url).hostname);
            } catch {
              return false;
            }
          });
          if (lan) {
            internal = `${lan.replace(/\/+$/, "")}/auth/connect/${encodeURIComponent(code)}`;
          }
        }
      } catch {
        /* the internal link is optional */
      }
      return {
        external: `https://${host}:${service.port}/auth/connect/${encodeURIComponent(code)}`,
        ...(internal ? { internal } : {}),
        expiresIn,
      };
    }
    case "snippet.write": {
      const exists = await fileExists(join(dir, USERS_FILE));
      const users = exists ? await readUsers(dir) : [];
      const content = caddySnippet(users);
      const path = join(dir, SNIPPET_FILE);
      let previous = "";
      try {
        previous = await readFile(path, "utf8");
      } catch {
        previous = "";
      }
      if (!exists && previous.trim()) {
        throw new Error(
          `${USERS_FILE} is missing — refusing to empty the live Caddy snippet.`,
        );
      }
      if (previous !== content) await atomicWrite(path, content);
      return {
        path,
        count: content ? content.trimEnd().split("\n").length : 0,
        changed: previous !== content,
      };
    }
    case "caddy.validate":
      return run(validateCommand(api), dir);
    case "caddy.reload": {
      const expectedUsers = caddySnippet(await readUsers(dir));
      let currentUsers = "";
      try {
        currentUsers = await readFile(join(dir, SNIPPET_FILE), "utf8");
      } catch {
        currentUsers = "";
      }
      if (!currentUsers)
        throw new Error("Write the users snippet before reloading Caddy.");
      if (currentUsers !== expectedUsers) {
        throw new Error(
          "The users snippet is stale — press Write users snippet before reloading Caddy.",
        );
      }
      if (await fileExists(join(dir, SERVICES_FILE))) {
        const expectedServices = caddyServicesSnippet(
          await readServices(dir),
          join(dir, SNIPPET_FILE),
        );
        let currentServices = "";
        try {
          currentServices = await readFile(
            join(dir, SERVICES_SNIPPET_FILE),
            "utf8",
          );
        } catch {
          currentServices = "";
        }
        if (!currentServices) {
          throw new Error("Write the services snippet before reloading Caddy.");
        }
        if (currentServices !== expectedServices) {
          throw new Error(
            "The services snippet is stale — press Write services snippet before reloading Caddy.",
          );
        }
        const services = await readServices(dir);
        const siteServices = services.filter(
          (service) => service.kind === "site",
        );
        if (siteServices.length > 0) {
          const host = siteHost(api);
          if (!host) {
            throw new Error(
              "Set the public URL before reloading a site service.",
            );
          }
          const expectedSites = caddySitesSnippet(
            services,
            host,
            join(dir, SNIPPET_FILE),
          );
          let currentSites = "";
          try {
            currentSites = await readFile(
              join(dir, SITES_SNIPPET_FILE),
              "utf8",
            );
          } catch {
            currentSites = "";
          }
          if (!currentSites) {
            throw new Error("Write the sites snippet before reloading Caddy.");
          }
          if (currentSites !== expectedSites) {
            throw new Error(
              "The sites snippet is stale — press Write services snippet before reloading Caddy.",
            );
          }
        }
      }
      return validateThenReload(
        (command) => run(command, dir),
        validateCommand(api),
        reloadCommand(api),
      );
    }
    case "status":
      return status(api);
    default:
      throw new Error(`Unknown action: ${action || "(none)"}`);
  }
}

